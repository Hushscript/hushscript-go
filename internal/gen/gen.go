// Package gen holds the pure parts of the generator: it validates the API spec and the shared hints
// and emits the Go source of the error catalog, the operation scope map and the hints table.
// scripts/generate.go is the command that wraps it with file and network access.
package gen

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"maps"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

const (
	// DefaultSpec is where the generator fetches the API spec from when it is given no path.
	DefaultSpec = "https://api.hushscript.com/openapi.json"
	// ConformanceRef is the tag of the conformance repository that hints.json is read from. It must
	// equal the tag in compose.yaml.
	ConformanceRef = "v0.1.0"

	header = "// Code generated by scripts/generate.go. DO NOT EDIT.\n\n"
)

var pathVariable = regexp.MustCompile(`\{([^}]+)\}`)

// ParseSpec decodes the spec, keeping numbers exact.
func ParseSpec(text []byte) (map[string]any, error) {
	decoder := json.NewDecoder(bytes.NewReader(text))
	decoder.UseNumber()
	var spec map[string]any
	if err := decoder.Decode(&spec); err != nil {
		return nil, fmt.Errorf("spec is not valid JSON: %w", err)
	}
	if spec == nil {
		return nil, errors.New("spec must be an object")
	}
	return spec, nil
}

func asObject(value any, what string) (map[string]any, error) {
	object, ok := value.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("%s must be an object", what)
	}
	return object, nil
}

func asString(value any, what string) (string, error) {
	text, ok := value.(string)
	if !ok || text == "" {
		return "", fmt.Errorf("%s must be a non-empty string", what)
	}
	return text, nil
}

func asInteger(value any, what string) (int, error) {
	number, ok := value.(json.Number)
	if !ok {
		return 0, fmt.Errorf("%s must be an integer", what)
	}
	parsed, err := strconv.Atoi(number.String())
	if err != nil {
		return 0, fmt.Errorf("%s must be an integer", what)
	}
	return parsed, nil
}

func formatSource(source string) ([]byte, error) {
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return nil, fmt.Errorf("emitted source does not parse: %w", err)
	}
	return formatted, nil
}

// EmitCatalog returns generated/catalog.go: the error catalog as a lookup by slug.
func EmitCatalog(spec map[string]any) ([]byte, error) {
	catalog, ok := spec["x-error-catalog"].([]any)
	if !ok || len(catalog) == 0 {
		return nil, errors.New("spec has no x-error-catalog")
	}
	seen := map[string]bool{}
	var entries strings.Builder
	for index, raw := range catalog {
		where := fmt.Sprintf("x-error-catalog[%d]", index)
		entry, err := asObject(raw, where)
		if err != nil {
			return nil, err
		}
		slug, err := asString(entry["slug"], where+".slug")
		if err != nil {
			return nil, err
		}
		if seen[slug] {
			return nil, fmt.Errorf("duplicate error slug %s", slug)
		}
		seen[slug] = true
		code, err := asInteger(entry["code"], slug+".code")
		if err != nil {
			return nil, err
		}
		status, err := asInteger(entry["status"], slug+".status")
		if err != nil {
			return nil, err
		}
		meaning, err := asString(entry["meaning"], slug+".meaning")
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&entries, "\t%s: {Code: %d, Status: %d, Meaning: %s},\n",
			strconv.Quote(slug), code, status, strconv.Quote(meaning))
	}
	return formatSource(header + `package generated

import (
	"maps"
	"slices"
)

// ErrorCatalogEntry is one entry of the API's x-error-catalog.
type ErrorCatalogEntry struct {
	Code    int
	Status  int
	Meaning string
}

var errorCatalog = map[string]ErrorCatalogEntry{
` + entries.String() + `}

// LookupError returns the catalog entry for an error slug.
func LookupError(slug string) (ErrorCatalogEntry, bool) {
	entry, ok := errorCatalog[slug]
	return entry, ok
}

// ErrorSlugs lists every slug in the catalog, sorted.
func ErrorSlugs() []string {
	return slices.Sorted(maps.Keys(errorCatalog))
}
`)
}

// operations lists the "METHOD /path" key of every operation in the spec with its scope, if any.
func operations(spec map[string]any) (map[string]string, error) {
	paths, err := asObject(spec["paths"], "paths")
	if err != nil {
		return nil, err
	}
	scopes := map[string]string{}
	for path, item := range paths {
		operationsOfPath, err := asObject(item, "paths."+path)
		if err != nil {
			return nil, err
		}
		for _, method := range httpMethods {
			operation, present := operationsOfPath[method]
			if !present {
				continue
			}
			where := method + " " + path
			object, err := asObject(operation, where)
			if err != nil {
				return nil, err
			}
			scope, present := object["x-required-scope"]
			if !present {
				continue
			}
			text, err := asString(scope, where+" x-required-scope")
			if err != nil {
				return nil, err
			}
			scopes[strings.ToUpper(method)+" "+path] = text
		}
	}
	return scopes, nil
}

var httpMethods = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}

// EmitScopes returns generated/scopes.go: the permission each operation needs, keyed "METHOD /path".
func EmitScopes(spec map[string]any) ([]byte, error) {
	scopes, err := operations(spec)
	if err != nil {
		return nil, err
	}
	var entries strings.Builder
	for _, key := range slices.Sorted(maps.Keys(scopes)) {
		fmt.Fprintf(&entries, "\t%s: %s,\n", strconv.Quote(key), strconv.Quote(scopes[key]))
	}
	return formatSource(header + `package generated

import (
	"maps"
	"slices"
)

var operationScopes = map[string]string{
` + entries.String() + `}

// RequiredScope returns the permission an operation needs, keyed "METHOD /path/{template}".
func RequiredScope(operation string) (string, bool) {
	scope, ok := operationScopes[operation]
	return scope, ok
}

// ScopedOperations lists every operation that declares a scope, sorted.
func ScopedOperations() []string {
	return slices.Sorted(maps.Keys(operationScopes))
}
`)
}

// ParseHints decodes hints.json: a flat object of slug to text.
func ParseHints(text []byte) (map[string]string, error) {
	var raw map[string]any
	if err := json.Unmarshal(text, &raw); err != nil {
		return nil, fmt.Errorf("hints.json is not valid JSON: %w", err)
	}
	if len(raw) == 0 {
		return nil, errors.New("hints.json is empty")
	}
	hints := make(map[string]string, len(raw))
	for slug, value := range raw {
		hint, err := asString(value, "hints."+slug)
		if err != nil {
			return nil, err
		}
		hints[slug] = hint
	}
	return hints, nil
}

// EmitHints returns generated/hints.go: the shared English hint text by error slug.
func EmitHints(hints map[string]string) ([]byte, error) {
	if len(hints) == 0 {
		return nil, errors.New("hints.json is empty")
	}
	var entries strings.Builder
	for _, slug := range slices.Sorted(maps.Keys(hints)) {
		if slug == "" || hints[slug] == "" {
			return nil, fmt.Errorf("hints.%s must be a non-empty string", slug)
		}
		fmt.Fprintf(&entries, "\t%s: %s,\n", strconv.Quote(slug), strconv.Quote(hints[slug]))
	}
	return formatSource(header + `package generated

import (
	"maps"
	"slices"
)

var hints = map[string]string{
` + entries.String() + `}

// Hint returns the shared hint text for an error slug.
func Hint(slug string) (string, bool) {
	text, ok := hints[slug]
	return text, ok
}

// HintSlugs lists every slug that has a hint, sorted.
func HintSlugs() []string {
	return slices.Sorted(maps.Keys(hints))
}
`)
}

// declaredPathParameters names the path parameters an operation declares itself or inherits from its path item.
func declaredPathParameters(spec map[string]any, lists ...any) (map[string]bool, error) {
	declared := map[string]bool{}
	for _, list := range lists {
		parameters, present := list.([]any)
		if !present {
			continue
		}
		for _, raw := range parameters {
			parameter, err := asObject(raw, "parameter")
			if err != nil {
				return nil, err
			}
			if reference, isReference := parameter["$ref"].(string); isReference {
				resolved, err := resolveParameter(spec, reference)
				if err != nil {
					return nil, err
				}
				parameter = resolved
			}
			if parameter["in"] == "path" {
				name, err := asString(parameter["name"], "path parameter name")
				if err != nil {
					return nil, err
				}
				declared[name] = true
			}
		}
	}
	return declared, nil
}

func resolveParameter(spec map[string]any, reference string) (map[string]any, error) {
	const prefix = "#/components/parameters/"
	name, found := strings.CutPrefix(reference, prefix)
	if !found {
		return nil, fmt.Errorf("unsupported parameter reference %s", reference)
	}
	components, err := asObject(spec["components"], "components")
	if err != nil {
		return nil, err
	}
	parameters, err := asObject(components["parameters"], "components.parameters")
	if err != nil {
		return nil, err
	}
	return asObject(parameters[name], reference)
}

// PatchPathParameters declares every path template variable that an operation leaves undeclared, as
// a required string parameter, because oapi-codegen refuses a path with an undeclared variable. It
// returns the patched spec as JSON for the generator's private copy (openapi.json itself is never
// touched) and the operations it changed. A declared path parameter that is not in the template is
// an error: that is a different defect, and guessing would hide it.
func PatchPathParameters(spec map[string]any) (patchedSpec []byte, changed []string, err error) {
	paths, err := asObject(spec["paths"], "paths")
	if err != nil {
		return nil, nil, err
	}
	for _, path := range slices.Sorted(maps.Keys(paths)) {
		item, itemErr := asObject(paths[path], "paths."+path)
		if itemErr != nil {
			return nil, nil, itemErr
		}
		var template []string
		for _, match := range pathVariable.FindAllStringSubmatch(path, -1) {
			template = append(template, match[1])
		}
		for _, method := range httpMethods {
			raw, present := item[method]
			if !present {
				continue
			}
			operation, operationErr := asObject(raw, method+" "+path)
			if operationErr != nil {
				return nil, nil, operationErr
			}
			declared, declaredErr := declaredPathParameters(spec, item["parameters"], operation["parameters"])
			if declaredErr != nil {
				return nil, nil, declaredErr
			}
			for _, name := range slices.Sorted(maps.Keys(declared)) {
				if !slices.Contains(template, name) {
					return nil, nil, fmt.Errorf("%s %s declares path parameter %q that is not in the path", strings.ToUpper(method), path, name)
				}
			}
			for _, name := range template {
				if declared[name] {
					continue
				}
				parameters, _ := operation["parameters"].([]any)
				operation["parameters"] = append(parameters, map[string]any{
					"name":     name,
					"in":       "path",
					"required": true,
					"schema":   map[string]any{"type": "string"},
				})
				changed = append(changed, strings.ToUpper(method)+" "+path+" ("+name+")")
			}
		}
	}
	text, err := json.Marshal(spec)
	if err != nil {
		return nil, nil, fmt.Errorf("re-encoding the patched spec: %w", err)
	}
	return text, changed, nil
}
